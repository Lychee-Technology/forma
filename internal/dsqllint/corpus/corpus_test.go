func TestRenderLabelsEveryStatementWithItsOrigin(t *testing.T) {
	u := Unit{Name: "sample", Statements: Transaction("cmd/tools/init_db.go:ensureTables",
		Statement{Origin: "internal/rowguard/ddl.go:tableDDL", SQL: "CREATE TABLE t (a INT);\n"},
	)}
	got, err := u.Render()
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	want := "-- Forma DSQL lint corpus unit sample (generated by TestDSQLCorpus; do not edit)\n" +
		"-- origin: cmd/tools/init_db.go:ensureTables\nBEGIN;\n" +
		"-- origin: internal/rowguard/ddl.go:tableDDL\nCREATE TABLE t (a INT);\n" +
		"-- origin: cmd/tools/init_db.go:ensureTables\nCOMMIT;\n"
	if got != want {
		t.Fatalf("Render =\n%s\nwant\n%s", got, want)
	}
}

func TestRenderRefusesWhatCannotBeLinted(t *testing.T) {
	ok := Statement{Origin: "a/b.go:F", SQL: "SELECT 1"}
	tests := []struct {
		name string
		unit Unit
		want string
	}{
		{"bad name", Unit{Name: "Bad Name", Statements: []Statement{ok}}, "lower-case"},
		{"no statements", Unit{Name: "empty"}, "no statements"},
		{"bad origin", Unit{Name: "u", Statements: []Statement{{Origin: "init_db", SQL: "SELECT 1"}}}, "not a path/file.go:Symbol"},
		{"empty sql", Unit{Name: "u", Statements: []Statement{{Origin: "a/b.go:F", SQL: " ; "}}}, "is empty"},
		{"unrendered verb", Unit{Name: "u", Statements: []Statement{{Origin: "a/b.go:F", SQL: "SELECT * FROM %s"}}}, "unrendered format verb"},
		{"fmt error marker", Unit{Name: "u", Statements: []Statement{{Origin: "a/b.go:F", SQL: "SELECT %!d(string=x)"}}}, "unrendered format verb"},
		{"comment only", Unit{Name: "u", Statements: []Statement{{Origin: "a/b.go:F", SQL: "-- no statement"}}}, "holds 0 executable statements"},
		{"block comment only", Unit{Name: "u", Statements: []Statement{{Origin: "a/b.go:F", SQL: "/* x */ ; /* y */"}}}, "holds 0 executable statements"},
		{"two statements", Unit{Name: "u", Statements: []Statement{{Origin: "a/b.go:F", SQL: "SELECT 1; SELECT 2"}}}, "holds 2 executable statements"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			_, err := tt.unit.Render()
			if err == nil || !strings.Contains(err.Error(), tt.want) {
				t.Fatalf("Render error = %v, want one containing %q", err, tt.want)
			}
		})
	}
}

func TestExportWritesOnlyWhenAsked(t *testing.T) {
	u := Unit{Name: "one", Statements: []Statement{{Origin: "a/b.go:F", SQL: "SELECT 1"}}}

	t.Setenv(CorpusDirEnv, "")
	Export(t, u) // renders, writes nothing

	dir := t.TempDir()
	t.Setenv(CorpusDirEnv, dir)
	Export(t, u)
	data, err := os.ReadFile(filepath.Join(dir, "one.sql"))
	if err != nil {
		t.Fatalf("read exported unit: %v", err)
	}
	if !strings.Contains(string(data), "-- origin: a/b.go:F\nSELECT 1;\n") {
		t.Fatalf("exported unit = %q", data)
	}
	if err := writeExclusive(filepath.Join(dir, "one.sql"), "x"); err == nil || !strings.Contains(err.Error(), "another unit has this name") {
		t.Fatalf("a second unit named one must be refused, got %v", err)
	}
}

func TestRecorderTakesStatementsInOrder(t *testing.T) {
	var r Recorder
	_ = r.Match("ignored", "SELECT 1")
	_ = r.Match("ignored", "SELECT 2")
	got := r.Take(t, "a.go:F", "a.go:G")
	if got[0].SQL != "SELECT 1" || got[1].Origin != "a.go:G" || r.SQL != nil {
		t.Fatalf("Take = %+v, recorder left %q", got, r.SQL)
	}
}

func TestCountStatements(t *testing.T) {
	for text, want := range map[string]int{
		"":                                  0,
		"-- c\n/* d */ ;\n":                 0,
		"SELECT 1":                          1,
		"SELECT ';' FROM t; -- x;\n":        1,
		"SELECT \"a;b\" FROM t; SELECT 2;":  2,
		"DO $$ BEGIN; END $$; SELECT $1":    2,
		"SELECT 'it''s; fine'":              1,
		"/* a; b */ SELECT 1 /* ; */ ; ; ;": 1,
		"SELECT 1; -- trailing\n/* c */":    1,
	} {
		if got := CountStatements(text); got != want {
			t.Errorf("CountStatements(%q) = %d, want %d", text, got, want)
		}
	}
}
