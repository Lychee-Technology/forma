// Package corpus is the export side of the Aurora DSQL lint gate (#740).
//
// The gate lints SQL that Forma's Go code generates, not a copy of it. Each
// package whose generators can reach Aurora DSQL has TestDSQLCorpus tests
// (every test whose name starts with TestDSQLCorpus) that call those
// generators with representative arguments and hand the statements to
// Export. Run normally, a test only checks that rendering succeeds; run by
// the gate with CorpusDirEnv set, it also writes one .sql file per unit into
// that directory, each statement preceded by an origin
// comment naming the generator, so a diagnostic can be traced back to it.
package corpus

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"sync"
	"testing"
)

// CorpusDirEnv names the directory the gate asks TestDSQLCorpus tests to
// write their units into. Unset, Export writes nothing.
const CorpusDirEnv = "FORMA_DSQL_CORPUS_DIR"

// OriginPrefix starts the comment line that names the generator of the
// statement after it.
const OriginPrefix = "-- origin: "

// Statement is one SQL statement and the generator that produced it.
type Statement struct {
	// Origin is an inventory location, "path/to/file.go:Symbol" relative to
	// the repository root: the function or constant that produces SQL.
	Origin string
	// SQL is the statement as Forma sends it. A trailing semicolon is
	// optional.
	SQL string
}

// Unit is one corpus file: statements Forma sends together, in order.
type Unit struct {
	// Name is the file stem, unique across the whole corpus.
	Name       string
	Statements []Statement
}

var (
	unitName = regexp.MustCompile(`^[a-z0-9][a-z0-9-]*$`)
	origin   = regexp.MustCompile(`^[A-Za-z0-9_./-]+\.go:[A-Za-z_][A-Za-z0-9_.]*$`)
	// fmtVerb catches a statement whose fmt.Sprintf template was not filled
	// in: a stray verb or a fmt error marker means the render went wrong.
	fmtVerb = regexp.MustCompile(`%(\[\d+\])?[sdvqx]|%!`)
)

// Transaction wraps body in the BEGIN and COMMIT its caller sends around it,
// both attributed to origin, the code that opens the transaction. Rendering
// the boundary lets dsql-lint check DSQL's one-DDL-per-transaction rule.
func Transaction(origin string, body ...Statement) []Statement {
	out := make([]Statement, 0, len(body)+2)
	out = append(out, Statement{Origin: origin, SQL: "BEGIN"})
	out = append(out, body...)
	return append(out, Statement{Origin: origin, SQL: "COMMIT"})
}

// Render answers u as the text of its corpus file, or an error when u is
// empty, misnamed, or holds a statement that did not render.
func (u Unit) Render() (string, error) {
	if !unitName.MatchString(u.Name) {
		return "", fmt.Errorf("corpus unit name %q must be lower-case letters, digits and dashes", u.Name)
	}
	if len(u.Statements) == 0 {
		return "", fmt.Errorf("corpus unit %s has no statements", u.Name)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "-- Forma DSQL lint corpus unit %s (generated by TestDSQLCorpus; do not edit)\n", u.Name)
	for i, st := range u.Statements {
		if !origin.MatchString(st.Origin) {
			return "", fmt.Errorf("corpus unit %s statement %d: origin %q is not a path/file.go:Symbol location", u.Name, i+1, st.Origin)
		}
		sql := strings.TrimRight(strings.TrimSpace(st.SQL), "; \t\n")
		if sql == "" {
			return "", fmt.Errorf("corpus unit %s statement %d (%s) is empty", u.Name, i+1, st.Origin)
		}
		// A comment-only value would be labelled and counted, yet lint
		// nothing; two statements under one label would be counted as one.
		if n := CountStatements(sql); n != 1 {
			return "", fmt.Errorf("corpus unit %s statement %d (%s) holds %d executable statements, want exactly 1: %s", u.Name, i+1, st.Origin, n, sql)
		}
		if fmtVerb.MatchString(sql) {
			return "", fmt.Errorf("corpus unit %s statement %d (%s) holds an unrendered format verb: %s", u.Name, i+1, st.Origin, sql)
		}
		fmt.Fprintf(&b, "%s%s\n%s;\n", OriginPrefix, st.Origin, sql)
	}
	return b.String(), nil
}

// Export renders u and, when CorpusDirEnv is set, writes it to that
// directory as <name>.sql. Any failure fails tb: the gate must never lint a
// partial corpus. Two units with one name fail the second export.
func Export(tb testing.TB, u Unit) {
	tb.Helper()
	text, err := u.Render()
	if err != nil {
		tb.Fatalf("render DSQL lint corpus: %v", err)
	}
	dir := os.Getenv(CorpusDirEnv)
	if dir == "" {
		return
	}
	if err := writeExclusive(filepath.Join(dir, u.Name+".sql"), text); err != nil {
		tb.Fatalf("export DSQL lint corpus unit %s: %v", u.Name, err)
	}
}

func writeExclusive(path, text string) error {
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
	if errors.Is(err, os.ErrExist) {
		return fmt.Errorf("%s already exists: another unit has this name", path)
	}
	if err != nil {
		return fmt.Errorf("create %s: %w", path, err)
	}
	if _, err := f.WriteString(text); err != nil {
		_ = f.Close()
		return fmt.Errorf("write %s: %w", path, err)
	}
	if err := f.Close(); err != nil {
		return fmt.Errorf("close %s: %w", path, err)
	}
	return nil
}

// Recorder captures the SQL a mocked connection receives, for generators
// that build their statement inline and send it themselves. Its Match method
// has the signature of both pgxmock.QueryMatcherFunc and
// sqlmock.QueryMatcherFunc, so a mock built with it accepts every statement
// and records it in order; the test still scripts the results the code under
// test reads back. A WireConn records into it too, so the statements pgx
// writes and those a mock receives interleave in the order they were sent.
type Recorder struct {
	mu   sync.Mutex
	SQL  []string
	errs []error
}

// Match records actual and accepts it.
func (r *Recorder) Match(_, actual string) error {
	spikeOnMatch(r, false)
	r.mu.Lock()
	defer r.mu.Unlock()
	r.SQL = append(r.SQL, actual)
	return nil
}

// matchWire is Match for the corpus wire's server goroutine (spike).
func (r *Recorder) matchWire(actual string) {
	spikeOnMatch(r, true)
	r.mu.Lock()
	defer r.mu.Unlock()
	r.SQL = append(r.SQL, actual)
}

func (r *Recorder) fail(err error) {
	r.mu.Lock()
	defer r.mu.Unlock()
	r.errs = append(r.errs, err)
}

// Take answers the recorded statements attributed to origins, one origin
// per statement in order, and clears the recorder. A count mismatch fails
// tb: the code under test sent more or fewer statements than the test names.
func (r *Recorder) Take(tb testing.TB, origins ...string) []Statement {
	tb.Helper()
	r.mu.Lock()
	defer r.mu.Unlock()
	if len(r.errs) > 0 {
		tb.Fatalf("recording failed: %v", errors.Join(r.errs...))
	}
	if len(r.SQL) != len(origins) {
		tb.Fatalf("recorded %d statements, test names origins for %d: %q", len(r.SQL), len(origins), r.SQL)
	}
	spikeOnTake(tb, r, r.SQL, origins)
	out := make([]Statement, len(origins))
	for i, o := range origins {
		out[i] = Statement{Origin: o, SQL: r.SQL[i]}
	}
	r.SQL = nil
	return out
}
