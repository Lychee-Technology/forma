// TestFindingsTraceToTheGeneratorAndTheKnownList is the generated-SQL half
// of the regression (#740): a diagnostic on a rendered statement names the
// Go generator of that statement, a known finding accepts only its own
// generator and rule, and a known finding that no longer occurs is stale.
func TestFindingsTraceToTheGeneratorAndTheKnownList(t *testing.T) {
	origins, err := ReadOrigins(strings.NewReader(unitText))
	if err != nil {
		t.Fatalf("ReadOrigins: %v", err)
	}
	if origins.Statements != 3 {
		t.Fatalf("Statements = %d, want 3", origins.Statements)
	}
	for line, want := range map[int]string{1: "", 3: "cmd/tools/init_db.go:withTx", 5: "internal/rowguard/ddl.go:tableDDL", 7: "internal/rowguard/ddl.go:tableDDL", 9: "cmd/tools/init_db.go:eavIndexDDL"} {
		if got := origins.At(line); got != want {
			t.Errorf("At(%d) = %q, want %q", line, got, want)
		}
	}

	byFile, err := ParseLintOutput(1, []byte(lintJSON), []string{"u.sql"})
	if err != nil {
		t.Fatalf("ParseLintOutput: %v", err)
	}
	unit := target{path: "u.sql", origins: origins}
	var findings []Finding
	for _, d := range byFile["u.sql"] {
		findings = append(findings, Finding{File: "u.sql", Origin: unit.originAt(d.Line), Diagnostic: d})
	}
	known := []Known{
		{Origin: "cmd/tools/init_db.go:withTx", Rule: "multi_ddl_transaction", Issue: "#690"},
		{Origin: "cmd/tools/init_db.go:eavIndexDDL", Rule: "set_transaction", Issue: "#690"},
	}
	v := Judge(findings, known)
	if len(v.Accepted) != 1 || v.Accepted[0].Origin != "cmd/tools/init_db.go:withTx" {
		t.Errorf("Accepted = %+v", v.Accepted)
	}
	if len(v.Unexpected) != 1 || v.Unexpected[0].Origin != "cmd/tools/init_db.go:eavIndexDDL" || v.Unexpected[0].Rule != "index_async" {
		t.Errorf("Unexpected = %+v: another rule on a known generator must still fail", v.Unexpected)
	}
	if len(v.Stale) != 1 || v.Stale[0].Rule != "set_transaction" {
		t.Errorf("Stale = %+v", v.Stale)
	}
	report := FormatFinding(v.Unexpected[0])
	for _, want := range []string{"u.sql:9: [index_async]", "generated by: cmd/tools/init_db.go:eavIndexDDL", "suggestion:   Use ASYNC.", "statement:    CREATE INDEX i ON t (a);"} {
		if !strings.Contains(report, want) {
			t.Errorf("FormatFinding lacks %q:\n%s", want, report)
		}
	}
}

func TestParseKnownNeedsATrackingIssue(t *testing.T) {
	for _, text := range []string{
		"a.go:F index_async needs-an-issue note\n",
		"a.go:F index_async #690\n",
		"a.go:F index_async #690 x\na.go:F index_async #691 y\n",
	} {
		if _, err := ParseKnown(strings.NewReader(text)); err == nil {
			t.Errorf("ParseKnown(%q) accepted it", text)
		}
	}
	known, err := ParseKnown(strings.NewReader("# c\n\na.go:F index_async #690 init-db indexes\n"))
	if err != nil || len(known) != 1 || known[0].Issue != "#690" || known[0].Note != "init-db indexes" {
		t.Fatalf("ParseKnown = %+v, %v", known, err)
	}
}

// TestPostgresOnlySQLStaysOutOfTheCorpus pins the other half of the
// regression: SQL classified postgres-only (or anything but rendered) that
// shows up in the corpus fails the gate, as does a rendered generator the
// corpus lost.
func TestPostgresOnlySQLStaysOutOfTheCorpus(t *testing.T) {
	entries := []Entry{
		{Class: ClassRendered, Location: "internal/a.go:guard", Line: 1},
		{Class: ClassRendered, Location: "internal/a.go:lost", Line: 2},
		{Class: ClassPostgresOnly, Location: "internal/a.go:advisory", Line: 3},
	}
	origins := map[string]bool{"internal/a.go:guard": true, "internal/a.go:advisory": true, "internal/a.go:unknown": true}
	var got []string
	for _, p := range checkCorpusOrigins(entries, origins) {
		got = append(got, p.Error())
	}
	joined := strings.Join(got, "\n")
	for _, want := range []string{
		"internal/a.go:advisory is classified postgres-only, so its SQL must not be in the DSQL corpus",
		"internal/a.go:unknown is not in the inventory",
		"rendered location internal/a.go:lost (inventory line 2) is in no corpus unit",
	} {
		if !strings.Contains(joined, want) {
			t.Errorf("checkCorpusOrigins lacks %q:\n%s", want, joined)
		}
	}
	if len(got) != 3 {
		t.Errorf("checkCorpusOrigins reported %d problems, want 3", len(got))
	}
	if p := CheckKnownOrigins(entries, []Known{{Origin: "internal/a.go:advisory", Rule: "r", Line: 4}}); len(p) != 1 {
		t.Errorf("a known finding on postgres-only SQL must be refused, got %v", p)
	}
}

func wheelWith(t *testing.T, name string, body []byte) []byte {
	t.Helper()
	var buf bytes.Buffer
	zw := zip.NewWriter(&buf)
	w, err := zw.Create(name)
	if err != nil {
		t.Fatalf("zip create: %v", err)
	}
	if _, err := w.Write(body); err != nil {
		t.Fatalf("zip write: %v", err)
	}
	if err := zw.Close(); err != nil {
		t.Fatalf("zip close: %v", err)
	}
	return buf.Bytes()
}

func sha(data []byte) string {
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:])
}

func TestExtractBinaryVerifiesThePin(t *testing.T) {
	good := wheelWith(t, binaryInWheel, []byte("ELF"))
	if got, err := extractBinary(good, sha(good)); err != nil || string(got) != "ELF" {
		t.Fatalf("extractBinary = %q, %v", got, err)
	}
	if _, err := extractBinary(good, strings.Repeat("0", 64)); err == nil || !strings.Contains(err.Error(), "refusing an unverified download") {
		t.Fatalf("a hash mismatch must be refused, got %v", err)
	}
	other := wheelWith(t, "dsql_lint-9.9.9.data/scripts/dsql-lint", []byte("ELF"))
	if _, err := extractBinary(other, sha(other)); err == nil || !strings.Contains(err.Error(), "no "+binaryInWheel) {
		t.Fatalf("a wheel of another version must be refused, got %v", err)
	}
}

func TestWheelsPinEveryCIPlatform(t *testing.T) {
	for _, platform := range []string{"linux/amd64", "linux/arm64"} {
		w, ok := wheels[platform]
		if !ok {
			t.Fatalf("no pinned dsql-lint wheel for %s, which CI runs on", platform)
		}
		if !strings.Contains(w.URL, "dsql_lint-"+ToolVersion+"-") || len(w.SHA256) != 64 {
			t.Errorf("%s wheel %+v does not pin dsql-lint %s with a sha256", platform, w, ToolVersion)
		}
	}
}
